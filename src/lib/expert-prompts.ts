export function detectAcademicDiscipline(
  order: StudentOrder,
  override?: AcademicDiscipline
): Exclude<AcademicDiscipline, "auto"> {
  if (override && override !== "auto") {
    return override;
  }
  const haystack = `${order.moduleName} ${order.assignmentTitle} ${order.specialty} ${order.exerciseText.slice(0, 1200)}`.toLowerCase();

  const quantKeywords = [
    "تحليل المعطيات",
    "إحصاء",
    "احصاء",
    "اقتصاد قياسي",
    "قياسي",
    "انحدار",
    "تباين",
    "anova",
    "mco",
    "مالية",
    "تسيير مالي",
    "رياضيات",
    "بحوث العمليات",
    "احتمالات",
    "ارتباط",
    "سلاسل زمنية",
    "spss",
    "eviews",
    "معامل",
    "مصفوفة",
    "تقدير",
    "اختبار",
    "تنبؤ",
  ];
  if (quantKeywords.some((k) => haystack.includes(k))) {
    return "quantitative";
  }

  const accLegalKeywords = [
    "محاسبة",
    "تدقيق",
    "مراجعة حسابات",
    "جباية",
    "ضرائب",
    "قانون",
    "تشريع",
    "منازعات",
    "scf",
    "اهتلاك",
    "ميزانية",
    "قيد محاسبي",
  ];
  if (accLegalKeywords.some((k) => haystack.includes(k))) {
    return "accounting_legal";
  }

  const caseKeywords = [
    "دراسة حالة",
    "حالة تطبيقية",
    "مؤسسة",
    "شركة",
    "استراتيجية",
    "تسويق",
    "موارد بشرية",
    "تسيير",
    "إدارة",
    "ادارة",
    "swot",
    "pestel",
    "حوكمة",
    "جودة",
    "مشروع",
  ];
  if (caseKeywords.some((k) => haystack.includes(k))) {
    return "case_study";
  }

  return "theoretical_essay";
}

